export interface PokemonItem {
  id: string;
  dexNumber: number;
  name: string;
  generation: 1 | 2 | 3 | 4 | 5 | 6 | 7 | 8 | 9;
  region: 'Kanto' | 'Johto' | 'Hoenn' | 'Sinnoh' | 'Unova' | 'Kalos' | 'Alola' | 'Galar' | 'Paldea';
  types: string[];
  hp: number;
  attack: number;
  defense: number;
  spAttack: number;
  spDefense: number;
  speed: number;
  baseStatTotal: number;
  archetype: 'Physical Sweeper' | 'Special Sweeper' | 'Bulky Tank' | 'Physical Wall' | 'Special Wall' | 'Hazard Lead' | 'Speed Control' | 'Support' | 'Mixed Attacker';
  ability: string;
  evolutionStage: 'Starter' | 'Basic' | 'Stage 1' | 'Stage 2' | 'Legendary' | 'Mythical' | 'Paradox' | 'Single';
  isStarter?: boolean;
  isLegendary?: boolean;
  isParadox?: boolean;
  description: string;
  spriteUrl: string;
  color: string;
}

